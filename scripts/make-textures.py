"""Generate the brushed-emulsion edge mask, the emulsion mottle, the paper grain tile
and the home-screen icon.

Both are deterministic (fixed seeds), so re-running this script reproduces
the committed PNGs byte for byte on the same Pillow/NumPy versions.

    python3 scripts/make-textures.py
"""
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter
from PIL.PngImagePlugin import PngInfo

OUT = Path(__file__).resolve().parent.parent / "assets" / "img"
OUT.mkdir(parents=True, exist_ok=True)


def save(im, name, what, **kw):
    """Write a PNG that records its own origin (the provenance every shipped raster carries)."""
    info = PngInfo()
    info.add_text("impeccable:prompt", f"Procedural, not generated by an image model: {what} "
                  f"Made by scripts/make-textures.py ({name}); re-run the script to reproduce it.")
    im.save(OUT / name, optimize=True, pnginfo=info, **kw)


def smooth_noise(n, scale, rng):
    """1-D value noise of length n with features roughly `scale` px long."""
    pts = rng.random(n // scale + 3)
    x = np.arange(n) / scale
    i = x.astype(int)
    f = x - i
    f = f * f * (3 - 2 * f)
    return pts[i] * (1 - f) + pts[i + 1] * f


def row_noise(n, scale, rng, sharp=1.0):
    v = smooth_noise(n, scale, rng)
    return v ** sharp


def emulsion_mask(size=480, seed=11):
    """Alpha mask of a cyanotype coat laid with horizontal brush strokes.

    Left and right edges end in bristle streaks of uneven length (stroke
    starts and stops). Top and bottom edges wander, with dry-brush gaps that
    run along the stroke direction.
    """
    rng = np.random.default_rng(seed)
    h = w = size
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    rows, cols = np.arange(h), np.arange(w)

    def side_reach(n):
        # Low-frequency wander plus per-bristle jitter (2-4 px features).
        return (
            26
            + 16 * row_noise(n, 120, rng)
            + 10 * row_noise(n, 3, rng, 1.8)
            + 5 * row_noise(n, 11, rng)
        )

    def cap_reach(n):
        return 24 + 15 * row_noise(n, 140, rng) + 6 * row_noise(n, 37, rng)

    left, right = side_reach(h), side_reach(h)
    top, bottom = cap_reach(w), cap_reach(w)
    d = np.minimum.reduce([
        xx - left[:, None],
        (w - 1 - xx) - right[:, None],
        yy - top[None, :],
        (h - 1 - yy) - bottom[None, :],
    ])
    alpha = np.clip(d / 2.2 + 0.5, 0, 1)

    # Dry-brush streaks: long along x, thin along y.
    streak = np.asarray(
        Image.fromarray((rng.random((h // 2, w // 40)) * 255).astype(np.uint8))
        .resize((w, h), Image.BICUBIC),
        dtype=np.float32,
    ) / 255.0
    near = np.clip(1 - np.maximum(d, 0) / 16.0, 0, 1)
    alpha = alpha * (1 - near * np.clip((0.55 - streak) * 1.6, 0, 0.85))

    # A few stray bristle hairs that overshoot the side edges.
    for side in (0, 1):
        for _ in range(26):
            y = int(rng.integers(30, h - 30))
            length = float(rng.uniform(6, 22))
            reach = (left if side == 0 else right)[y]
            x0 = reach - length
            x1 = reach + 2
            xs = np.arange(max(0, int(x0)), int(x1))
            fade = np.clip((xs - x0) / length, 0, 1) * rng.uniform(0.35, 0.8)
            col = xs if side == 0 else (w - 1 - xs)
            alpha[y, col] = np.maximum(alpha[y, col], fade)
    alpha = np.asarray(
        Image.fromarray((alpha * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.45)),
        dtype=np.float32,
    ) / 255.0
    rgba = np.zeros((h, w, 4), np.uint8)
    rgba[..., :3] = 255
    rgba[..., 3] = (alpha.clip(0, 1) * 255).astype(np.uint8)
    save(Image.fromarray(rgba, "RGBA"), "emulsion-edge.png",
         "alpha mask of a cyanotype coat with brushed edges, used as the CSS mask-border of every coat.")


def paper_grain(size=160, seed=5):
    rng = np.random.default_rng(seed)
    g = rng.normal(0, 1, (size, size)).astype(np.float32)
    g = np.asarray(Image.fromarray(((g * 0.5 + 0.5).clip(0, 1) * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.6)), dtype=np.float32) / 255.0
    # Tileable: blend with a half-shifted copy across the seams.
    shifted = np.roll(np.roll(g, size // 2, 0), size // 2, 1)
    w = np.minimum(np.arange(size), size - 1 - np.arange(size)) / (size / 2)
    m = np.minimum.outer(w, w)
    g = g * m + shifted * (1 - m)
    a = (np.abs(g - 0.5) * 2) ** 1.6 * 34  # sparse, faint fibres
    rgba = np.zeros((size, size, 4), np.uint8)
    rgba[..., :3] = np.where(g[..., None] > 0.5, 255, 11)
    rgba[..., 3] = a.clip(0, 255).astype(np.uint8)
    save(Image.fromarray(rgba, "RGBA"), "paper-grain.png",
         "tileable cotton-paper grain, faint light and dark fibres over the page ground.")


def band_noise(shape, sigma_y, sigma_x, rng):
    """Tileable noise: white noise low-passed in the frequency domain, so it wraps."""
    h, w = shape
    f = np.fft.fft2(rng.normal(0, 1, shape))
    fy = np.fft.fftfreq(h)[:, None]
    fx = np.fft.fftfreq(w)[None, :]
    f *= np.exp(-2 * (np.pi ** 2) * ((fy * sigma_y) ** 2 + (fx * sigma_x) ** 2))
    n = np.real(np.fft.ifft2(f))
    return n / np.abs(n).max()


def emulsion_mottle(name, light_max, dark_max, size=384, seed=23):
    """The inside of a coat: soft mottle plus horizontal brush streaks.

    White lightens, Prussian deep darkens, each up to the given alpha (0-255).
    The two strengths are set per surface so text on every coat keeps WCAG AA:
    the strong tile sits under white text on the field and the deep band, the
    soft one under the light and mid bands.
    """
    rng = np.random.default_rng(seed)
    mottle = band_noise((size, size), 30, 30, rng)
    streak = band_noise((size, size), 2.5, 70, rng)
    m = 0.55 * mottle + 0.45 * streak
    m = m / np.abs(m).max()
    # Push values toward the ends so most of the coat shows the texture, not only its peaks.
    m = np.tanh(1.8 * m) / np.tanh(1.8)
    steps = 24
    light = np.round(np.clip(m, 0, 1) * steps).astype(np.uint8)
    dark = np.round(np.clip(-m, 0, 1) * steps).astype(np.uint8)
    # An indexed PNG with per-entry transparency: white or deep at a few alphas.
    key = np.where(m > 0, light, np.where(dark > 0, steps + dark, 0)).astype(np.uint8)
    pal, alpha = [], []
    for i in range(steps + 1):
        pal += [255, 255, 255]
        alpha.append(round(i / steps * light_max))
    for i in range(1, steps + 1):
        pal += [11, 37, 89]
        alpha.append(round(i / steps * dark_max))
    im = Image.fromarray(key, "P")
    im.putpalette(pal)
    save(im, name,
         f"tileable emulsion mottle and horizontal brush streaks laid inside the cobalt coats "
         f"(lightens up to {light_max}/255, darkens up to {dark_max}/255).",
         transparency=bytes(alpha))


def touch_icon(size=180):
    """The favicon's sun mark at home-screen size."""
    s = size / 32
    im = Image.new("RGB", (size, size), "#163F94")
    d = ImageDraw.Draw(im)
    r, w = 9 * s, 3 * s
    c = size / 2
    d.ellipse((c - r - w / 2, c - r - w / 2, c + r + w / 2, c + r + w / 2), fill="#F3F6F9")
    d.ellipse((c - r + w / 2, c - r + w / 2, c + r - w / 2, c + r - w / 2), fill="#163F94")
    d.ellipse((c - 3.2 * s, c - 3.2 * s, c + 3.2 * s, c + 3.2 * s), fill="#E0E46A")
    save(im, "apple-touch-icon.png", "home-screen icon, the favicon's sun mark at 180px.")


if __name__ == "__main__":
    emulsion_mask()
    paper_grain()
    emulsion_mottle("emulsion-mottle.png", light_max=45, dark_max=84)
    emulsion_mottle("emulsion-mottle-soft.png", light_max=24, dark_max=54)
    touch_icon()
    print("wrote", OUT / "emulsion-edge.png", OUT / "paper-grain.png", OUT / "emulsion-mottle.png",
          OUT / "emulsion-mottle-soft.png", OUT / "apple-touch-icon.png")
